async function call(name: string, raw: unknown): Promise<unknown> {
  switch (name) {
    case "list_apps": {
      parseArgs(schemas.list_apps, raw);
      return { apps: await listSources() };
    }

    case "get_app": {
      const args = parseArgs(schemas.get_app, raw);
      const app = await findApp(args.app);
      return getSource(app.id);
    }

    case "create_app": {
      const args = parseArgs(schemas.create_app, raw);
      const template = parseAppTemplate(args.template);
      const created = await createSource({
        name: template.app.name,
        kind: "http",
        baseUrl: template.app.baseUrl,
        auth: template.app.auth ?? { type: "none" },
        headers: template.app.headers ?? {},
        exposeAll: false,
        tools: template.tools.map((tool) => ({
          name: tool.name,
          description: tool.description,
          method: tool.method,
          path: tool.path,
          sideEffect: tool.sideEffect,
          inputSchema: tool.inputSchema,
          exposed: tool.exposed ?? true,
        })),
      });
      return {
        appId: created.source.id,
        name: created.source.name,
        slug: created.source.slug,
        tools: created.tools.map((tool) => ({
          displayName: tool.displayName,
          mcpName: tool.mcpName,
        })),
      };
    }

    case "export_app": {
      const args = parseArgs(schemas.export_app, raw);
      const app = await findApp(args.app);
      const detail = await getSource(app.id);
      return {
        format: "plexus.app.v1",
        exportedAt: new Date().toISOString(),
        app: {
          id: detail.source.id,
          name: detail.source.name,
          kind: detail.source.kind,
          baseUrl: detail.source.baseUrl,
        },
        tools: detail.tools.map((tool) => ({
          name: tool.name,
          description: tool.description,
          method: tool.method,
          path: tool.path,
          sideEffect: tool.sideEffect,
          inputSchema: tool.inputSchema,
          exposed: tool.exposed,
          enabled: tool.enabled,
        })),
      };
    }

    case "import_app": {
      const args = parseArgs(schemas.import_app, raw);
      const app = await findApp(args.app);
      if (!args.confirm) {
        const diff = await previewImport(app.id, args.config);
        return { applied: false, diff };
      }
      const result = await applyImport(app.id, args.config, args.removeMissing);
      return { applied: true, ...result };
    }

    case "list_tools": {
      const args = parseArgs(schemas.list_tools, raw);
      if (!args.app) return { tools: await listTools() };
      const app = await findApp(args.app);
      return { tools: await listTools(app.id) };
    }

    case "add_tool": {
      const args = parseArgs(schemas.add_tool, raw);
      const app = await findApp(args.app);
      const tool = await addTool(app.id, {
        name: args.name,
        method: args.method.toUpperCase(),
        path: args.path,
        description: args.description,
        sideEffect: args.sideEffect,
        inputSchema: args.inputSchema,
        exposed: args.exposed,
        enabled: args.enabled,
      });
      return { tool };
    }

    case "update_tool": {
      const args = parseArgs(schemas.update_tool, raw);
      const tool = await findTool(args.tool);
      const { tool: _ref, ...patch } = args;
      return { tool: await updateTool(tool.id, patch) };
    }

    case "delete_tool": {
      const args = parseArgs(schemas.delete_tool, raw);
      const tool = await findTool(args.tool);
      const usage: ToolUsage = await getToolUsage(tool.id);
      if (!args.confirm) {
        return { deleted: false, tool: tool.displayName, usage };
      }
      await deleteTool(tool.id);
      return { deleted: true, tool: tool.displayName, usage };
    }

    case "list_grants": {
      const args = parseArgs(schemas.list_grants, raw);
      const app = await findApp(args.app);
      const toolIds = await getAppGrants(app.id);
      const all = await listTools();
      const byId = new Map(all.map((tool) => [tool.id, tool.displayName]));
      return { app: app.name, tools: toolIds.map((id) => byId.get(id) ?? id) };
    }

    case "set_grants": {
      const args = parseArgs(schemas.set_grants, raw);
      const app = await findApp(args.app);
      const ids: string[] = [];
      for (const ref of args.tools) ids.push((await findTool(ref)).id);
      const toolIds = await setAppGrants(app.id, ids);
      return { app: app.name, toolIds };
    }

    case "create_token": {
      const args = parseArgs(schemas.create_token, raw);
      const sourceIds: string[] = [];
      for (const ref of args.apps ?? []) sourceIds.push((await findApp(ref)).id);
      return createToken({
        name: args.name,
        scope: args.scope,
        sourceIds,
      });
    }

    case "invoke_tool": {
      const args = parseArgs(schemas.invoke_tool, raw);
      const tool = await findTool(args.tool);
      const key =
        args.idempotencyKey ?? `admin-mcp:${randomUUID()}`;
      const result = await invokeTool({
        toolId: tool.id,
        args: args.args,
        via: "api",
        scope: "write",
        idempotencyKey: key,
        actorType: "user",
        actorId: "admin-mcp",
      });
      return result;
    }

    case "list_invocations": {
      const args = parseArgs(schemas.list_invocations, raw);
      const sourceId = args.app ? (await findApp(args.app)).id : undefined;
      return listInvocations({
        limit: args.limit,
        ...(sourceId ? { sourceId } : {}),
        ...(args.status ? { status: args.status } : {}),
        ...(args.actor ? { actorType: args.actor } : {}),
      });
    }

    default:
      throw new AppError("not_found", 404, `Unknown admin tool: ${name}`);
  }
}

function errorText(err: unknown): string {
  if (isAppError(err)) {
    const details = err.details ? `\n${JSON.stringify(err.details, null, 2)}` : "";
    return `${err.message}${err.hint ? `\n${err.hint}` : ""}${details}`;
  }
  return "Admin tool failed";
}

function buildServer(): Server {
  const server = new Server(
    { name: "plexus-admin", version: config.version },
    {
      capabilities: { tools: {} },
      instructions:
        "Administration endpoint for this Plexus instance. Destructive tools (delete_tool, import_app) only act with confirm=true; call them without confirm first to inspect the impact.",
    },
  );

  server.setRequestHandler(ListToolsRequestSchema, async () => ({ tools: definitions }));

  server.setRequestHandler(CallToolRequestSchema, async (request) => {
    try {
      const result = await call(request.params.name, request.params.arguments ?? {});
      const text = JSON.stringify(result ?? null, null, 2);
      const structured =
        result && typeof result === "object" && !Array.isArray(result)
          ? (result as Record<string, unknown>)
          : { result };

      return {
        content: [
          {
            type: "text" as const,
            text:
              text.length > MAX_TEXT
                ? `${text.slice(0, MAX_TEXT)}\n…[truncated ${
                    text.length - MAX_TEXT
                  } chars]`
                : text,
          },
        ],
        structuredContent: structured,
        isError: false,
      };
    } catch (err) {
      return {
        content: [{ type: "text" as const, text: errorText(err) }],
        isError: true,
      };
    }
  });

  return server;
}

/** Handle one stateless admin MCP request. */
export async function handleAdminMcpRequest(request: Request): Promise<Response> {
  const server = buildServer();
  const transport = new WebStandardStreamableHTTPServerTransport({
    sessionIdGenerator: undefined,
    enableJsonResponse: true,
  });

  try {
    await server.connect(transport);
    return await transport.handleRequest(request);
  } finally {
    await transport.close().catch(() => undefined);
    await server.close().catch(() => undefined);
  }
}
