const MAX_TEXT = 60_000;

function parseArgs<S extends z.ZodTypeAny>(schema: S, raw: unknown): z.output<S> {
  const parsed = schema.safeParse(raw ?? {});
  if (!parsed.success) {
    const issues = parsed.error.issues
      .map((issue) => `${issue.path.join(".") || "(root)"}: ${issue.message}`)
      .join("; ");
    throw new AppError("invalid_request", 400, `Invalid arguments — ${issues}`);
  }
  return parsed.data as z.output<S>;
}

async function findApp(ref: string) {
  const apps = await listSources();
  const matches = apps.filter(
    (app) => app.id === ref || app.name === ref || app.slug === ref,
  );
  if (matches.length === 0) throw new AppError("not_found", 404, `App not found: ${ref}`);
  if (matches.length > 1) throw new AppError("invalid_request", 400, `Ambiguous app: ${ref}`);
  return matches[0]!;
}

async function findTool(ref: string) {
  const all = await listTools();
  const matches = all.filter(
    (tool) =>
      tool.id === ref ||
      tool.mcpName === ref ||
      tool.displayName === ref ||
      tool.name === ref,
  );
  if (matches.length === 0) throw new AppError("not_found", 404, `Tool not found: ${ref}`);
  if (matches.length > 1) {
    throw new AppError(
      "invalid_request",
      400,
      `Ambiguous tool: ${ref} (${matches.map((tool) => tool.displayName).join(", ")})`,
    );
  }
  return matches[0]!;
}

const AppRef = z.string().min(1).max(128);
const ToolRef = z.string().min(1).max(128);

const schemas = {
  list_apps: z.object({}),
  get_app: z.object({ app: AppRef }),
  create_app: z.object({ template: z.string().min(1).max(2_000_000) }),
  export_app: z.object({ app: AppRef }),
  import_app: z.object({
    app: AppRef,
    config: z.string().min(1).max(2_000_000),
    removeMissing: z.boolean().default(false),
    confirm: z.boolean().default(false),
  }),
  list_tools: z.object({ app: AppRef.optional() }),
  add_tool: z.object({
    app: AppRef,
    name: z.string().min(1).max(64),
    method: z.string().default("POST"),
    path: z.string().min(1).max(500),
    description: z.string().max(2000).default(""),
    sideEffect: z.enum(["read", "write"]).default("read"),
    inputSchema: z.unknown().optional(),
    exposed: z.boolean().default(true),
    enabled: z.boolean().default(true),
  }),
  update_tool: z.object({
    tool: ToolRef,
    name: z.string().min(1).max(64).optional(),
    method: z.string().optional(),
    path: z.string().min(1).max(500).optional(),
    description: z.string().max(2000).optional(),
    sideEffect: z.enum(["read", "write"]).optional(),
    inputSchema: z.unknown().optional(),
    exposed: z.boolean().optional(),
    enabled: z.boolean().optional(),
  }),
  delete_tool: z.object({ tool: ToolRef, confirm: z.boolean().default(false) }),
  list_grants: z.object({ app: AppRef }),
  set_grants: z.object({ app: AppRef, tools: z.array(ToolRef).max(200) }),
  create_token: z.object({
    name: z.string().min(1).max(64),
    scope: z.enum(["read", "write"]).default("read"),
    apps: z.array(AppRef).max(100).optional(),
  }),
  invoke_tool: z.object({
    tool: ToolRef,
    args: z.record(z.unknown()).default({}),
    idempotencyKey: z.string().min(8).max(200).optional(),
  }),
  list_invocations: z.object({
    app: AppRef.optional(),
    status: z.enum(["ok", "error", "replayed"]).optional(),
    actor: z.enum(["user", "mcp", "app", "agent"]).optional(),
    limit: z.number().int().min(1).max(200).default(20),
  }),
};

