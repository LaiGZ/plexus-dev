import type { AppTemplate, TemplatePreview, ToolPreview } from "@plexus/contracts";
import { AppTemplate as AppTemplateSchema } from "@plexus/contracts";
import { parse as parseYaml } from "yaml";
import { badRequest } from "../../infra/errors.js";
import { slugify } from "./service.js";

/**
 * Downloadable creation template.
 *
 * `app_id` is deliberately absent: the platform generates it when the app is
 * created. Comments are part of the product here — the file is meant to be
 * edited by hand.
 */
export const APP_TEMPLATE = `# ─────────────────────────────────────────────────────────────
# Plexus app template
#
# 1. Fill in the app section and the methods you want to expose.
# 2. Keep this file, then use "Import template" on the Connect app page.
# 3. The platform generates the app_id — never put one in this file.
#
# JSON works too, but YAML keeps these comments.
# ─────────────────────────────────────────────────────────────
format: plexus.template.v1

app:
  # Shown in the UI and used as the tool-name prefix: finance.listBills.
  # ASCII names give the cleanest prefix.
  name: Finance

  # Base address of the service; method paths are appended to it.
  baseUrl: http://127.0.0.1:7001

  # Optional upstream credentials. Leave the whole block out for no auth.
  # auth:
  #   type: bearer        # none | bearer | basic | header
  #   token: sk-...
  #
  # auth:
  #   type: basic
  #   username: demo
  #   password: demo
  #
  # auth:
  #   type: header
  #   headerName: x-api-key
  #   headerValue: ...

tools:
  # Each entry becomes one tool. Names must be unique within the app.
  - name: listBills
    description: List bills
    method: POST                # GET | POST | PUT | PATCH | DELETE
    path: /api/listBills
    sideEffect: read            # read | write
    exposed: true               # visible to the assistant and MCP clients
    enabled: true
    inputSchema:
      type: object
      properties: {}

  - name: createBill
    description: Create a bill
    method: POST
    path: /api/createBill
    sideEffect: write           # writes ask for approval / need a write token
    exposed: true
    enabled: true
    inputSchema:
      type: object
      properties:
        amount:
          type: number
          description: Amount in yuan
        note:
          type: string
      required: [amount]
`;

export function parseAppTemplate(text: string): AppTemplate {
  let raw: unknown;
  try {
    raw = parseYaml(text);
  } catch {
    throw badRequest("Template is not valid YAML or JSON");
  }

  const parsed = AppTemplateSchema.safeParse(raw);
  if (!parsed.success) {
    throw badRequest(
      "Template is missing required fields",
      parsed.error.issues.map((issue) => ({
        path: issue.path.join("."),
        message: issue.message,
      })),
      "Start from the downloaded template; app_id is generated by the platform",
    );
  }

  const names = new Set<string>();
  for (const tool of parsed.data.tools) {
    if (names.has(tool.name)) {
      throw badRequest(`Duplicate method in template: ${tool.name}`);
    }
    names.add(tool.name);
  }

  return parsed.data;
}

export function templatePreview(template: AppTemplate): TemplatePreview {
  const slug = slugify(template.app.name);
  const taken = new Set<string>();

  const tools: ToolPreview[] = template.tools.map((tool) => {
    const base = `${slug}__${tool.name}`.slice(0, 64);
    let mcpName = base;
    let suffix = 2;
    while (taken.has(mcpName)) {
      mcpName = `${base.slice(0, 60)}_${suffix}`;
      suffix += 1;
    }
    taken.add(mcpName);

    return {
      name: tool.name,
      mcpName,
      description: tool.description,
      method: tool.method,
      path: tool.path,
      sideEffect: tool.sideEffect,
      inputSchema: tool.inputSchema ?? { type: "object", properties: {} },
      exposed: tool.exposed,
    };
  });

  const warnings: string[] = [];
  if (template.app.auth && template.app.auth.type !== "none") {
    warnings.push(
      "The template contains credentials. They are stored encrypted and never exported again.",
    );
  }

  return {
    app: {
      name: template.app.name,
      baseUrl: template.app.baseUrl,
      ...(template.app.auth ? { auth: template.app.auth } : {}),
      ...(template.app.headers ? { headers: template.app.headers } : {}),
    },
    tools,
    warnings,
  };
}
